import assert from 'node:assert/strict';
import {normalizeAccounting,accountingAction as act} from './accounting-data.mjs';
import {UNITS,budgetRows,decide} from './executive-data.mjs';
let db=normalizeAccounting(),checks=0;
const ok=f=>{f();checks++;};
const p={unit:UNITS[0],year:2026,date:'2026-11-03',voucher:'QA-001',content:'Chi thử',value:1000000};
ok(()=>assert.equal(budgetRows(db,2026,UNITS[0])[0].available,840000000));
ok(()=>assert.throws(()=>act(db,'expense',{...p,value:900000000}),/Vượt/));
db=act(db,'queue',{...p,value:900000000});const q=db.paymentQueue[0];
ok(()=>assert.equal(budgetRows(db,2026,UNITS[0])[0].available,840000000));
ok(()=>assert.throws(()=>act(db,'expense',{...p,id:q.id,value:900000000}),/Vượt/));
db=act(db,'receipt',{...p,voucher:'THU-01'});
ok(()=>assert.equal(budgetRows(db,2026,UNITS[0])[0].available,840000000));
ok(()=>assert.throws(()=>act(db,'receipt',{...p,voucher:'thu-01'}),/tồn tại/));
ok(()=>assert.throws(()=>act(db,'expense',{...p,voucher:'DATE-01',date:'2027-01-01'}),/Ngày/));
ok(()=>assert.throws(()=>act(db,'expense',{...p,value:-1}),/Số tiền/));
ok(()=>assert.throws(()=>act(db,'expense',p,0),/thay đổi/));
db=act(db,'draft',{title:'Bổ sung',purpose:'Phục vụ đào tạo',unit:UNITS[0],year:2026,items:[{name:'Máy tính',quantity:1,price:100000000}]});const r=db.requests.at(-1);
ok(()=>assert.equal(r.status,'draft'));
db=act(db,'submit',{id:r.id});ok(()=>assert.equal(db.requests.at(-1).status,'pending'));
ok(()=>assert.throws(()=>act(db,'submit',{id:r.id}),/nháp/));
ok(()=>assert.throws(()=>act(db,'draft',{...r,id:r.id}),/Chỉ sửa/));
db=decide(db,{id:r.id,version:db.requests.at(-1).version,status:'approved',opinion:'Duyệt'});
db=act(db,'expense',{...p,id:q.id,value:900000000});
ok(()=>assert.equal(db.paymentQueue[0].status,'paid'));
ok(()=>assert.equal(budgetRows(db,2026,UNITS[0])[0].available,40000000));
ok(()=>assert.throws(()=>act(db,'expense',{...p,id:q.id,value:1}),/tồn tại|xử lý/));
ok(()=>assert.throws(()=>act(db,'receipt',{...p,voucher:'X',date:'2026-02-30'}),/Ngày/));
console.log(`PASS ${checks} kiểm tra kế toán`);

