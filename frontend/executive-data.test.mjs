import assert from 'node:assert/strict';
import {createSeed,amount,budgetRows,decide,validDatabase} from './executive-data.mjs';
const seed=createSeed(),request=seed.requests.find(r=>r.id==='DT-2026-014');
const sum=db=>budgetRows(db,2026).reduce((s,r)=>s+r.total,0);
assert.equal(validDatabase(seed),true);
assert.equal(amount(request),400000000);
assert.equal(sum(seed),7800000000);
assert.equal(budgetRows(seed,2026).reduce((s,r)=>s+r.spent,0),5160000000);
const approved=decide(seed,{id:request.id,version:1,status:'approved',opinion:'Đồng ý hồ sơ đã trình.'});
assert.equal(sum(approved),8200000000);
assert.equal(sum(seed),7800000000);
assert.equal(approved.requests.find(r=>r.id===request.id).version,2);
assert.throws(()=>decide(approved,{id:request.id,version:1,status:'approved',opinion:'Duyệt lại'}),/đã được xử lý/);
assert.throws(()=>decide(seed,{id:request.id,version:0,status:'approved',opinion:'Sai phiên bản'}),/đã được xử lý/);
assert.throws(()=>decide(seed,{id:request.id,version:1,status:'rejected',opinion:'  '}),/lý do/);
const rejected=decide(seed,{id:request.id,version:1,status:'rejected',opinion:'Cần bổ sung hồ sơ.'});
assert.equal(sum(rejected),7800000000);
assert.equal(rejected.requests.find(r=>r.id===request.id).opinion,'Cần bổ sung hồ sơ.');
assert.equal(budgetRows(seed,2027).length,0);
assert.equal(budgetRows(seed,2026,'Khoa CNTT')[0].available,840000000);
assert.equal(budgetRows(seed,2026,'Đơn vị ngoài phạm vi').length,0);
assert.equal(rejected.revision,1);
console.log('PASS: 16 kiểm tra dữ liệu Ban Giám hiệu (tổng tiền, phê duyệt, từ chối, phiên bản, phạm vi, không ghi đè).');
