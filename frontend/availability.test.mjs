import assert from 'node:assert/strict';
import {freeIntervals,overlaps,fitsInterval,holdsRoom} from './availability.mjs';
const booked=(start,end,status='pending')=>({start,end,status});
assert.deepEqual(freeIntervals([booked('07:00','11:30')]),[{start:'11:30',end:'18:00'}]);
const split=freeIntervals([booked('07:00','08:30'),booked('09:30','11:30')]);
assert.deepEqual(split,[{start:'08:30',end:'09:30'},{start:'11:30',end:'18:00'}]);
assert.equal(fitsInterval(split,'08:30','09:30'),true);
assert.equal(fitsInterval(split,'08:29','09:30'),false);
assert.equal(fitsInterval(split,'08:30','09:31'),false);
assert.equal(overlaps('07:00','08:30','08:30','09:30'),false);
assert.equal(overlaps('08:30','09:30','09:30','11:30'),false);
assert.equal(overlaps('07:00','11:30','08:30','09:30'),true);
assert.deepEqual(freeIntervals([booked('09:30','11:30'),booked('07:00','08:30'),booked('08:00','10:00')]),[{start:'11:30',end:'18:00'}]);
assert.deepEqual(freeIntervals([booked('06:00','19:00')]),[]);
assert.deepEqual(freeIntervals([booked('07:00','18:00','cancelled'),booked('07:00','18:00','draft'),booked('07:00','18:00','rejected')]),[{start:'07:00',end:'18:00'}]);
assert.equal(holdsRoom('pending'),true);
assert.equal(holdsRoom('approved'),true);
assert.equal(fitsInterval(split,'10:00','09:00'),false);
console.log('PASS: 14 interval assertions, including both requested examples and adjacent boundaries.');
