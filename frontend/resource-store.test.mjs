import assert from 'node:assert/strict';
import {normalizeResources,manageResources,deviceFree,roomReservations,overdue} from './resource-store.mjs';
import {TODAY} from './resource-seed.mjs';
import {freeIntervals} from './availability.mjs';
let count=0;
const eq=(a,b)=>{assert.deepEqual(a,b);count++;};
const fails=(fn,pattern)=>{assert.throws(fn,pattern);count++;};
const now=new Date(TODAY+'T07:00'),seed=normalizeResources();
const change=(d,action,p,t=now)=>manageResources(d,action,p,d.resourceRevision,t);
const future=new Date(now);future.setDate(future.getDate()+5);
const day=`${future.getFullYear()}-${String(future.getMonth()+1).padStart(2,'0')}-${String(future.getDate()).padStart(2,'0')}`;
eq(seed.catalog.rooms.length,7);eq(seed.assets.length,7);
eq(normalizeResources(seed).requests,seed.requests);
let d=change(seed,'review',{id:'TB-2026-003',status:'approved',notes:'Đủ điều kiện.'});
eq(d.requests.find(r=>r.id==='TB-2026-003').status,'approved');
eq(seed.requests.find(r=>r.id==='TB-2026-003').status,'pending');
fails(()=>change(d,'review',{id:'TB-2026-003',status:'approved',notes:'Lặp'}),/không còn/);
fails(()=>manageResources(d,'review',{},0,now),/đã thay đổi/);
eq(change(seed,'review',{id:'TB-2026-003',status:'rejected',notes:' '}).requests.find(r=>r.id==='TB-2026-003').reason,'');
eq(change(seed,'review',{id:'TB-2026-003',status:'rejected',notes:'Cần làm rõ.'}).requests.find(r=>r.id==='TB-2026-003').reason,'Cần làm rõ.');
fails(()=>change(d,'handover',{id:'TB-2026-003',quantity:2,notes:'Tốt'}),/khớp/);
d=change(d,'handover',{id:'TB-2026-003',quantity:1,notes:'Tốt, đủ phụ kiện.'});
eq(d.requests.find(r=>r.id==='TB-2026-003').status,'ready');
eq(d.requests.find(r=>r.id==='TB-2026-003').handover.quantity,1);
fails(()=>change(d,'handover',{id:'TB-2026-003',quantity:1,notes:'Tốt'}),/đã duyệt/);
eq(overdue(seed.requests.find(r=>r.id==='TB-2026-004'),now),true);
eq(deviceFree(seed,'MIC01',day,'08:00','09:00'),2);
let rt=normalizeResources(seed),loan=rt.requests.find(r=>r.id==='TB-2026-004');
loan.status='return_pending';loan.returnRequest={quantity:2,good:1,damaged:1,lost:0,notes:'Hỏng một chiếc'};
fails(()=>change(rt,'return',{id:loan.id,good:3,damaged:0,lost:0,notes:'Sai số'}),/Số lượng/);
rt=change(rt,'return',{id:loan.id,good:0,damaged:1,lost:0,notes:'Nhận hỏng một bộ trước.'});
eq(rt.requests.find(r=>r.id===loan.id).returned,1);
eq(rt.requests.find(r=>r.id===loan.id).status,'borrowed');
eq(rt.catalog.devices.find(d=>d.id==='MIC01').available,3);
eq(deviceFree(rt,'MIC01',day,'08:00','09:00'),2);
eq(rt.assets.find(a=>a.device==='MIC01').unusable,1);
eq(rt.requests.find(r=>r.id===loan.id).returnHistory[0].overdue,true);
fails(()=>change(rt,'return',{id:loan.id,good:1,damaged:0,lost:0,notes:'Lặp'}),/Không có yêu cầu/);
rt.requests.find(r=>r.id===loan.id).status='return_pending';
rt.requests.find(r=>r.id===loan.id).returnRequest={quantity:1,good:1,damaged:0,lost:0};
rt=change(rt,'return',{id:loan.id,good:1,damaged:0,lost:0,notes:'Nhận bộ còn lại.'});
eq(rt.requests.find(r=>r.id===loan.id).status,'completed');
eq(deviceFree(rt,'MIC01',day,'08:00','09:00'),3);
const peak=normalizeResources(seed);peak.requests=peak.requests.filter(r=>r.resource!=='MIC01');
peak.requests.push(...[['08:00','09:00'],['09:00','10:00']].map(([start,end],i)=>({id:'S'+i,kind:'device',resource:'MIC01',date:day,start,end,quantity:1,returned:0,status:'approved'})));
eq(deviceFree(peak,'MIC01',day,'08:00','10:00'),3);
let room=normalizeResources(seed);room.requests.push({id:'P-1',kind:'room',resource:'A201',name:'A201',date:TODAY,start:'08:00',end:'09:00',students:20,status:'pending'});
fails(()=>change(room,'review',{id:'P-1',status:'approved',notes:'Duyệt'}),/trùng/);
fails(()=>change(seed,'room',{id:'B201',edit:true,name:'Phòng máy',building:'Nhà B',seats:10,type:'Phòng máy',available:true}),/Sức chứa/);
fails(()=>change(seed,'room',{id:'A201',edit:true,name:'A201',building:'Nhà A',seats:60,type:'Phòng học',available:false}),/lịch hiệu lực/);
room=change(seed,'room',{id:'D101',name:'Phòng D.101',building:'Nhà D',seats:50,type:'Phòng học',available:true,tags:'Máy chiếu'});
eq(room.catalog.rooms.at(-1).id,'D101');
fails(()=>change(seed,'room',{id:'A401',edit:true,name:'A401',building:'Nhà A',seats:60,type:'Phòng học',available:true}),/tài sản cố định/);
fails(()=>change(room,'room',{id:'D101',name:'Trùng',building:'Nhà D',seats:50,type:'Phòng học',available:true}),/đã tồn tại/);
let inv=change(seed,'inventory-create',{name:'Kiểm kê thử',unit:'Phòng Quản trị',date:TODAY});
eq(inv.inventories[0].rows[0].expected,5);
const invID=inv.inventories[0].id,blank=inv.inventories[0].rows.map(r=>({id:r.id,actual:'',condition:'',notes:''}));
fails(()=>change(inv,'inventory-save',{id:invID,rows:blank,finish:true}),/chưa ghi nhận/);
const diff=blank.map((r,i)=>({...r,actual:i?inv.inventories[0].rows[i].expected:4,condition:'Tốt'}));
eq(change(inv,'inventory-save',{id:invID,rows:diff,finish:true}).inventories[0].status,'completed');
diff[0].notes='Thiếu một bộ, đang đối chiếu.';
inv=change(inv,'inventory-save',{id:invID,rows:diff,finish:true});
eq(inv.inventories[0].status,'completed');eq(inv.assets[0].quantity,5);
fails(()=>change(inv,'inventory-save',{id:invID,rows:diff}),/đã hoàn tất/);
let m=change(seed,'asset',{id:'TS-DH201',name:'Điều hòa A201',unit:'Phòng Quản trị',location:'A201',quantity:1,price:10000000,purchased:TODAY,room:'A201'});
m=change(m,'maintenance-plan',{asset:'TS-DH201',mode:'service',quantity:1,start:day+'T07:00',end:day+'T11:30',content:'Vệ sinh định kỳ.'});
eq(freeIntervals(roomReservations(m,'A201',day)),[{start:'11:30',end:'18:00'}]);
fails(()=>change(m,'maintenance-start',{id:m.maintenance[0].id}),/Chưa đến/);
fails(()=>change(m,'maintenance-plan',{asset:'TS-DH201',mode:'service',quantity:1,start:day+'T08:00',end:day+'T09:00',content:'Trùng lịch'}),/đã có kế hoạch/);
let active=change(m,'maintenance-start',{id:m.maintenance[0].id},new Date(day+'T07:05'));
eq(freeIntervals(roomReservations(active,'A201',day)),[]);
fails(()=>change(active,'maintenance-finish',{id:active.maintenance[0].id,cost:1.5,result:'good',notes:'Xong'}),/số nguyên/);
active=change(active,'maintenance-finish',{id:active.maintenance[0].id,cost:3000000,voucher:'CT-2026-016',result:'good',notes:'Hoạt động tốt.'},new Date(day+'T11:20'));
eq(active.maintenance[0].cost,3000000);eq(freeIntervals(roomReservations(active,'A201',day)),[{start:'07:00',end:'18:00'}]);
fails(()=>change(active,'maintenance-finish',{id:active.maintenance[0].id,cost:0,result:'good',notes:'Xong'}),/đang thực hiện/);
let repair=change(rt,'maintenance-plan',{asset:'TS-MIC01',mode:'repair',quantity:1,start:day+'T07:00',end:day+'T08:00',content:'Sửa micro hỏng.'});
eq(deviceFree(repair,'MIC01',day,'07:00','08:00'),3);
repair=change(repair,'maintenance-start',{id:repair.maintenance[0].id},new Date(day+'T07:00'));
repair=change(repair,'maintenance-finish',{id:repair.maintenance[0].id,cost:0,result:'good',notes:'Sửa xong.'},new Date(day+'T08:00'));
eq(repair.catalog.devices.find(d=>d.id==='MIC01').available,4);
let log=change(seed,'log',{id:'NK-001',status:'needs_update',notes:'Bổ sung diễn giải.'});eq(log.logs[0].status,'needs_update');
fails(()=>change(log,'log',{id:'NK-001',status:'confirmed',notes:'Lặp'}),/không còn/);
eq(change(seed,'reminder',{id:'TB-2026-004',notes:'Nhắc kiểm tra thiết bị.'}).requests.find(r=>r.id==='TB-2026-004').reminder.notes,'Nhắc kiểm tra thiết bị.');
console.log(`PASS: ${count} kiểm tra quản lý phòng/tài sản, mượn trả, kiểm kê, bảo trì và dữ liệu dùng chung.`);
